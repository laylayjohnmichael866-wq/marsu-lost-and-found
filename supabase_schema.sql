-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.item_reports (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  owner_name text not null,
  report_type text not null check (report_type in ('lost', 'found')),
  item_name text not null,
  category text not null,
  description text not null,
  incident_date timestamptz not null,
  general_location text not null,
  image_path text,
  status text not null default 'open' check (status in ('open', 'claimPending', 'returned', 'closed')),
  created_at timestamptz not null default now(),
  is_flagged boolean not null default false
);

alter table public.item_reports enable row level security;

create policy "Authenticated users can view reports"
  on public.item_reports for select to authenticated using (true);

create policy "Users can create their own reports"
  on public.item_reports for insert to authenticated
  with check ((select auth.uid()) = owner_id);

create policy "Users can update their own reports"
  on public.item_reports for update to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

create policy "Admins can moderate reports"
  on public.item_reports for update to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

-- Keep the existing bucket private. These policies allow authenticated users
-- to upload only beneath their own auth UID, and authenticated users to view
-- images through signed URLs generated by the client SDK.
create policy "Users can upload their own report images"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'lost-found-images'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

create policy "Authenticated users can view report images"
  on storage.objects for select to authenticated
  using (bucket_id = 'lost-found-images');

create policy "Users can delete their own report images"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'lost-found-images'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
